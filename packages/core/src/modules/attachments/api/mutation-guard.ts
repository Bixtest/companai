import { NextResponse } from 'next/server'
import type { AwilixContainer } from 'awilix'
import { runRouteMutationGuards } from '@open-mercato/shared/lib/crud/route-mutation-guard'

type GuardOperation = 'create' | 'update' | 'delete' | 'custom'

type AttachmentsMutationGuardContext = {
  container: AwilixContainer
  /** Verified tenant id (from the resolved auth context / route scope). */
  tenantId: string | null | undefined
  /** Organization the write is scoped to, if any. */
  organizationId?: string | null
  /** Actor id — the authenticated user id (`auth.sub`). */
  userId: string | null | undefined
  req: Request
  /**
   * The resource kind the guard set is evaluated against, shaped
   * `<module>.<entity>`. Only two kinds are written by this module:
   *
   * - `attachments.attachment` — a file record (upload / metadata update /
   *   transfer / delete)
   * - `attachments.partition` — a storage partition (create / update / delete)
   */
  resourceKind: string
  /** The id the guard set is evaluated against. */
  resourceId: string
  operation: GuardOperation
  mutationPayload?: Record<string, unknown> | null
}

type AttachmentsMutationGuardHandle = {
  blockedResponse: NextResponse | null
  /**
   * Runs every registry guard's `afterSuccess` callback. Call only after the
   * write commits.
   *
   * Pass `resourceIdOverride` when the final resource id is only known *after*
   * the write (e.g. the multipart upload POST, whose `Attachment.id` is
   * generated by `randomUUID()` before `em.create`). The guard was validated
   * against the id available at check time, but `afterSuccess` receives
   * `resourceId`, so it is re-bound here. Re-running the guard set on a fresh
   * collection is safe **by contract**: `MutationGuard.validate` is a pure
   * predicate that reads the payload and returns a decision; only `afterSuccess`
   * acts.
   */
  runAfterSuccess: (resourceIdOverride?: string | null) => Promise<void>
}

/**
 * Runs the structural mutation guards for every `attachments` write route.
 *
 * **D2-gap (2026-10-07). Closed.** All **8** of this module's write verbs called
 * **no mutation guard at all** — not this module's wrapper (none existed), not
 * `runRouteMutationGuards()`, not the `@deprecated` pair D2-wide retired, and
 * they are not built by `makeCrudRoute`. A string scan of the whole module found
 * **no guard symbol of any kind**. So a guard set shipped for
 * `attachments.attachment` / `attachments.partition` would have been
 * **silently skipped**, and an AI/Hermes-authorized upload, metadata edit,
 * transfer or delete would have reached the database — and, for uploads and
 * deletes, the storage driver — with the registry chokepoint never consulting
 * it. Upload and delete are the highest-consequence writes in the product: one
 * publishes a file to a storage partition, the other removes both the row and
 * the backing file.
 *
 * **Measured after this wiring:** `attachments` **8 → 0** unguarded (all 8 now
 * `GUARDED_WRAPPER`); wrapper class for the module **0 → 8**; total D2-gap
 * **58 → 50**; repo-wide wrapper class **+8**; guarded-only **+8**; closure
 * `58 → 50` on the unguarded term. Next-largest remaining module: `search` (7)
 * / `webhooks` (7).
 *
 * **Test evidence — two disjoint mutations, not a mock.**
 * `api/__tests__/d2-gap-wiring.route.test.ts` registers a **real** guard in the
 * global store via `registerMutationGuards()` and drives the **real** handlers
 * with `runRouteMutationGuards` **unmocked**. Mutation 1 (**block**) asserts the
 * guard's status is returned and the **write never happens** (the entity manager
 * records no create/persist/flush/remove); mutation 2 (**allow**) asserts the
 * write happens **and** `afterSuccess` fires **exactly once**. Three disjoint
 * mutations proved the suite bites, each file restored **byte-identical** after
 * the run.
 *
 * **What was NOT missing — stated plainly, because the label invites the
 * opposite reading.** Every one of the eight verbs **already enforces its own
 * capability** through `metadata.requireFeatures`, and every row lookup carries
 * **tenant + organization scope**:
 *
 * | File | Verb | Feature today |
 * |---|---|---|
 * | `api/route.ts` | POST (upload) / DELETE | `attachments.manage` |
 * | `api/partitions/route.ts` | POST / PUT / DELETE | `attachments.manage` |
 * | `api/library/[id]/route.ts` | PATCH / DELETE | `attachments.manage` |
 * | `api/transfer/route.ts` | POST | `attachments.manage` |
 *
 * The defect was the **missing structural chokepoint**, not missing
 * authorization. This wrapper is that joint; it does not replace the feature
 * checks above, and it does not re-implement any route's own validation
 * (multipart checks, quota, dangerous-extension and active-content filters,
 * partition-lock, default-partition protection, in-use checks), optimistic-lock
 * handling or audit story.
 *
 * **`resourceKind` — the design decision.** Each route passes the kind that
 * names the row it actually writes, so a guard registered against e.g.
 * `attachments.partition` sees *that* write and not a neighbouring attachment:
 *
 * - `attachments.attachment` — `api/route.ts` POST (upload) + DELETE,
 *   `api/library/[id]/route.ts` PATCH + DELETE, `api/transfer/route.ts` POST.
 *   The transfer moves N attachment rows, so it is guarded once per *request*,
 *   against the shared record kind — the row-level ids travel in the payload.
 * - `attachments.partition` — `api/partitions/route.ts` POST + PUT + DELETE.
 *   A partition is a storage-topology object; its id in the guard is the
 *   partition **`code`** (the stable, business-meaningful key the route's own
 *   audit entries already use as `resourceId`), falling back to the row id when
 *   a code is not resolvable.
 *
 * **What this wrapper does NOT do.** It does not decide *whether* the caller
 * may write — that is the feature set above plus each route's own scope rules.
 * It runs the registry guard set and reports a block if one refuses. Guards are
 * **additional** policy, not a replacement.
 *
 * Same wrapper shape as the fifteen migrated before it — the worked example
 * (`entities/api/definitions.mutation-guard.ts`, `d225602`), `data_sync`
 * (`c6c3151`), `dictionaries` (`43e4e5d`), `dashboards` (`a05ea2c`),
 * `workflows` (`d3af1b1`), `inbox_ops` (`d89b8f6`), `perspectives`
 * (`e26642c`), `translations` (`a2f8d5f`), `planner` (`641d3af`),
 * `query_index` (`cc5a237`), `auth` (`aeeaad0`), `directory` (`d682c09`),
 * `feature_toggles` (`5af76bc`), `audit_logs` (`4ef5812`) and `business_rules`
 * (`a2e7c13`).
 */
export async function beginAttachmentsMutationGuard(
  ctx: AttachmentsMutationGuardContext,
): Promise<AttachmentsMutationGuardHandle> {
  const { tenantId, userId } = ctx
  if (!tenantId || !userId) {
    // No verified tenant/actor — the guard set cannot be evaluated. The route's
    // own auth check is authoritative and returns before reaching here when the
    // actor is missing; this mirrors the legacy service's behaviour on
    // incomplete context rather than inventing a second auth mechanism.
    return { blockedResponse: null, runAfterSuccess: async () => undefined }
  }

  const callGuards = (resourceId: string) =>
    runRouteMutationGuards({
      container: ctx.container,
      req: ctx.req,
      auth: {
        userId,
        tenantId,
        organizationId: ctx.organizationId ?? null,
      },
      input: {
        resourceKind: ctx.resourceKind,
        resourceId,
        operation: ctx.operation,
        mutationPayload: ctx.mutationPayload ?? null,
      },
    })

  const guardResult = await callGuards(ctx.resourceId)

  if (!guardResult.ok) {
    return {
      blockedResponse: NextResponse.json(guardResult.errorBody, { status: guardResult.errorStatus }),
      runAfterSuccess: async () => undefined,
    }
  }

  return {
    blockedResponse: null,
    runAfterSuccess: async (resourceIdOverride?: string | null) => {
      if (resourceIdOverride == null || resourceIdOverride === ctx.resourceId) {
        await guardResult.runAfterSuccess()
        return
      }
      // The write materialised a DB row whose id differs from the id validated
      // (the upload POST generates its `Attachment.id` with `randomUUID()`).
      // Re-collect the callbacks bound to the final id, then run them.
      // `validate` is a pure predicate (see the guard contract), so re-running
      // it has no effect.
      const rebound = await callGuards(resourceIdOverride)
      if (rebound.ok) await rebound.runAfterSuccess()
    },
  }
}
