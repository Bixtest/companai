import { NextResponse } from 'next/server'
import type { AwilixContainer } from 'awilix'
import { runRouteMutationGuards } from '@open-mercato/shared/lib/crud/route-mutation-guard'

type GuardOperation = 'create' | 'update' | 'delete' | 'custom'

type BusinessRulesMutationGuardContext = {
  container: AwilixContainer
  /** Verified tenant id (from the resolved auth context / route scope). */
  tenantId: string | null | undefined
  /** Organization the write is scoped to, if any. */
  organizationId?: string | null
  /** Actor id — the authenticated user id (`auth.sub`). */
  userId: string | null | undefined
  req: Request
  /**
   * The resource kind the guard set is evaluated against, shaped
   * `<module>.<entity>`: `business_rules.rule`, `business_rules.ruleSet`,
   * `business_rules.ruleSetMember`, `business_rules.executionLog`.
   */
  resourceKind: string
  /** The id the guard set is evaluated against. */
  resourceId: string
  operation: GuardOperation
  mutationPayload?: Record<string, unknown> | null
}

type BusinessRulesMutationGuardHandle = {
  blockedResponse: NextResponse | null
  /**
   * Runs every registry guard's `afterSuccess` callback. Call only after the
   * write commits.
   *
   * Pass `resourceIdOverride` when the final resource id is only known *after*
   * the write (e.g. a POST whose row id is generated by `em.create`). The guard
   * was validated against the id available at check time, but `afterSuccess`
   * receives `resourceId`, so it is re-bound here. Re-running the guard set on a
   * fresh collection is safe **by contract**: `MutationGuard.validate` is a pure
   * predicate that reads the payload and returns a decision; only `afterSuccess`
   * acts.
   */
  runAfterSuccess: (resourceIdOverride?: string | null) => Promise<void>
}

/**
 * Runs the structural mutation guards for every `business_rules` write route.
 *
 * **D2-gap (2026-10-07). Closed.** All **11** of this module's write verbs called
 * **no mutation guard at all** — not this module's wrapper (none existed), not
 * `runRouteMutationGuards()`, not the `@deprecated` pair D2-wide retired, and
 * they are not built by `makeCrudRoute`. So a guard set shipped for
 * `business_rules.*` would have been **silently skipped**, and an
 * AI/Hermes-authorized write to a rule — or a manual rule *execution* — would
 * have reached the database with the registry chokepoint never consulting it.
 *
 * **Measured after this wiring:** `business_rules` **11 → 0** unguarded (all 11
 * now `GUARDED_WRAPPER`); wrapper class for the module **0 → 11**; total D2-gap
 * **99 → 88**; repo-wide wrapper class **77 → 88**; guarded-only **149 → 160**;
 * closure **88 + 0 + 35 + 32 + 5 + 0 + 8 + 88 = 256**. Next-largest remaining
 * module: `inbox_ops` / `notifications` / `workflows` (**10** each).
 *
 * **Test evidence — two disjoint mutations, not a mock.**
 * `api/__tests__/d2-gap-wiring.route.test.ts` (**53 tests**) registers a **real**
 * guard in the global store via `registerMutationGuards()` and drives the
 * **real** handlers. Mutation 1 (**block**) asserts the guard's status is
 * returned and the **write never happens** (the entity manager records no
 * persist/flush/remove); mutation 2 (**allow**) asserts the write happens **and**
 * `afterSuccess` fires **exactly once**. Three disjoint mutations proved the
 * suite bites, each file restored **byte-identical** after the run
 * (wrapper md5 `6638a9593b5f4c4de210cc25a6b38eb3`, `rules/route.ts` md5
 * `5ef33481f290eae653c73e99546bff0a`):
 *
 * 1. neuter the wrapper's **block** path → exactly the **11 mutation-1** tests RED;
 * 2. remove the guard call from **one route file** (`rules/route.ts` POST) →
 *    exactly that route's **2 tests** RED, the other 9 verbs staying green;
 * 3. sever the wrapper's **whole `afterSuccess` path** → exactly the
 *    **11 mutation-2** tests RED. *(A first cut of this mutation severed only
 *    the direct branch and left the `resourceIdOverride` rebind branch intact —
 *    the two `execute` tests then stayed green. That was a real gap in the
 *    mutation's coverage, not a pass; the full sever was run and the count came
 *    to 11. Recorded because "the mutation found half a path" is exactly the
 *    kind of thing a re-run of one's own check would hide.)*
 *
 * `business_rules` **19 suites / 393 tests green**; core `tsc --noEmit` exit 0.
 *
 * **What was NOT missing — stated plainly, because the label invites the
 * opposite reading.** Every one of the eleven verbs **already enforces its own
 * capability** through `metadata.requireFeatures`, and every row lookup carries
 * **tenant + organization scope**:
 *
 * | File | Verb | Feature today |
 * |---|---|---|
 * | `rules/route.ts` | POST / PUT / DELETE | `business_rules.manage` |
 * | `sets/route.ts` | POST / PUT / DELETE | `business_rules.manage_sets` |
 * | `sets/[id]/members/route.ts` | POST / PUT / DELETE | `business_rules.manage_sets` |
 * | `execute/route.ts` | POST | `business_rules.execute` |
 * | `execute/[ruleId]/route.ts` | POST | `business_rules.execute` |
 *
 * The defect was the **missing structural chokepoint**, not missing
 * authorization. This wrapper is that joint; it does not replace the feature
 * checks above, and it does not re-implement any route's own validation,
 * optimistic-lock handling or audit story.
 *
 * **`resourceKind` — the design decision.** Each route passes the kind that
 * names the row it actually writes, so a guard registered against e.g.
 * `business_rules.rule` sees *that* write and not a neighbouring one:
 *
 * - `business_rules.rule` — a rule definition (create / update / soft-delete)
 * - `business_rules.ruleSet` — a rule set (create / update / soft-delete)
 * - `business_rules.ruleSetMember` — a rule's membership in a set (link /
 *   reorder / unlink)
 * - `business_rules.executionLog` — **the two `execute/*` POSTs.**
 *
 * **Why the two `execute/*` routes are guarded as a write, and why that is not
 * a false positive.** They look like "run something" calls, but both are
 * genuine DB writes: `ruleEngine.executeRules` / `executeRuleById` insert a
 * `RuleExecutionLog` row via `logRuleExecution` **whenever `dryRun` is false**
 * (verified in `lib/rule-engine.ts`, two call paths each). A guard set for this
 * module must therefore be able to see a manual execution — the log row is what
 * records *who ran which rule, on what data, and with what outcome*, and
 * `logRuleExecution` is also reached at the error/timeout exits. The kind used
 * is the log being written, not the rule being read. `dryRun: true` writes no
 * row, but the route is wired unconditionally (the guard is a *pre-write*
 * chokepoint; a dry-run request that is refused before any read is the correct
 * behaviour, and the alternative — reading the payload to decide — would put
 * policy decisions inside the route).
 *
 * **What this wrapper does NOT do.** It does not decide *whether* the caller
 * may write — that is the feature set above plus each route's own scope rules.
 * It runs the registry guard set and reports a block if one refuses. Guards are
 * **additional** policy, not a replacement.
 *
 * Same wrapper shape as the fourteen migrated before it — the worked example
 * (`entities/api/definitions.mutation-guard.ts`, `d225602`), `data_sync`
 * (`c6c3151`), `dictionaries` (`43e4e5d`), `dashboards` (`a05ea2c`),
 * `workflows` (`d3af1b1`), `inbox_ops` (`d89b8f6`), `perspectives`
 * (`e26642c`), `translations` (`a2f8d5f`), `planner` (`641d3af`),
 * `query_index` (`cc5a237`), `auth` (`aeeaad0`), `directory` (`d682c09`),
 * `feature_toggles` (`5af76bc`) and `audit_logs` (`4ef5812`).
 */
export async function beginBusinessRulesMutationGuard(
  ctx: BusinessRulesMutationGuardContext,
): Promise<BusinessRulesMutationGuardHandle> {
  const { tenantId, userId } = ctx
  if (!tenantId || !userId) {
    // No verified tenant/actor — the guard set cannot be evaluated. The route's
    // own auth check is authoritative and returns before reaching here when the
    // actor is missing; this mirrors the legacy service's behaviour on
    // incomplete context rather than inventing a second auth mechanism.
    return { blockedResponse: null, runAfterSuccess: async () => undefined }
  }

  const callGuards = (resourceId: string) =>
    runRouteMutationGuards({
      container: ctx.container,
      req: ctx.req,
      auth: {
        userId,
        tenantId,
        organizationId: ctx.organizationId ?? null,
      },
      input: {
        resourceKind: ctx.resourceKind,
        resourceId,
        operation: ctx.operation,
        mutationPayload: ctx.mutationPayload ?? null,
      },
    })

  const guardResult = await callGuards(ctx.resourceId)

  if (!guardResult.ok) {
    return {
      blockedResponse: NextResponse.json(guardResult.errorBody, { status: guardResult.errorStatus }),
      runAfterSuccess: async () => undefined,
    }
  }

  return {
    blockedResponse: null,
    runAfterSuccess: async (resourceIdOverride?: string | null) => {
      if (resourceIdOverride == null || resourceIdOverride === ctx.resourceId) {
        await guardResult.runAfterSuccess()
        return
      }
      // The write materialised a DB row whose id differs from the id validated
      // (a POST whose row id is generated by `em.create`). Re-collect the
      // callbacks bound to the final id, then run them. `validate` is a pure
      // predicate (see the guard contract), so re-running it has no effect.
      const rebound = await callGuards(resourceIdOverride)
      if (rebound.ok) await rebound.runAfterSuccess()
    },
  }
}
