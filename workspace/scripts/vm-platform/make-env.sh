#!/bin/sh
# Generates the .env for the WAN deployment. Run once, on the VM, in this
# directory:
#
#   ./make-env.sh <platform-host>
#
# <platform-host> is the name the platform answers on. For the first run with a
# Cloudflare quick tunnel, pass the tunnel hostname; later, the real domain.
#
# It refuses to overwrite an existing .env. That is deliberate: the secrets
# below are baked into the database on first boot. Re-running with new values
# would leave the seeded rows undecryptable — in particular TENANT_DATA_*
# encrypts tenant fields, so a changed key means the existing data cannot be
# read back. Delete .env by hand only if you mean to start the database over.
set -eu

if [ -f .env ]; then
  echo "refusing to overwrite the existing .env" >&2
  echo "the secrets in it are already baked into the seeded database" >&2
  exit 1
fi

HOST="${1:-platform.test}"

# hex only, so the values survive being pasted into a shell, a URL or a .env
# without quoting problems.
hex() { openssl rand -hex "${1:-32}"; }

cat > .env <<EOF
# WAN deployment of the Companai platform on the Platform-Server VM.
# Generated by make-env.sh — every value below is unique to this deployment.
# Do not commit. Do not copy to another deployment: the secrets are baked into
# the seeded database, and TENANT_DATA_ENCRYPTION_FALLBACK_KEY encrypts tenant
# fields, so reusing or changing them across deployments loses data.

# --- identity -------------------------------------------------------------
# Namespaces the image tag, container names, volume names and network name.
# The transferred image is tagged open-mercato/app:\${DEPLOY_ENV}.
DEPLOY_ENV=wan

# --- ports and resources --------------------------------------------------
# Publish on the VM's loopback only. The proxy reaches the app over the docker
# network, so nothing needs to be exposed on the VM's own interfaces.
APP_BIND=127.0.0.1
APP_PORT=3000
CONTAINER_PORT=3000
# This VM has ~4.7 GB of RAM available. The kit's default of 3072 assumes a
# 16 GB host and would let V8 grow until the kernel starts swapping.
APP_NODE_OPTIONS=--max-old-space-size=2048
REDIS_MAXMEMORY=256mb

# --- the name the platform answers on (rewritten by set-host.sh) ----------
PLATFORM_HOST=${HOST}
PLATFORM_HOST_ALT=${HOST}
PLATFORM_PRIMARY_HOST=${HOST}
PLATFORM_DOMAINS=localhost,127.0.0.1,${HOST}
APP_URL=https://${HOST}
# The app runs with NODE_ENV=development (the kit's compose sets it), and in
# dev mode it rejects requests from origins that are not listed here — this is
# what lets a remote visitor load the app at all. The wildcard covers a quick
# tunnel whose hostname changes when cloudflared restarts.
APP_ALLOWED_ORIGINS=*.trycloudflare.com,${HOST}

# --- database -------------------------------------------------------------
POSTGRES_USER=postgres
POSTGRES_PASSWORD=$(hex 32)
POSTGRES_DB=open-mercato

# --- secrets --------------------------------------------------------------
JWT_SECRET=$(hex 32)
NEXTAUTH_SECRET=$(hex 32)
# Encrypts tenant data at rest. The kit ships a public dev value here, which
# would leave the data effectively unprotected on a publicly reachable host.
TENANT_DATA_ENCRYPTION_KEY=$(hex 32)
TENANT_DATA_ENCRYPTION_FALLBACK_KEY=$(hex 32)
MEILISEARCH_MASTER_KEY=$(hex 32)

# --- first superadmin -----------------------------------------------------
# Read them back with:
#   grep OM_INIT_SUPERADMIN .env
OM_INIT_SUPERADMIN_EMAIL=admin@companai.local
OM_INIT_SUPERADMIN_PASSWORD=$(hex 16)

# --- behaviour ------------------------------------------------------------
DEMO_MODE=true
SELF_SERVICE_ONBOARDING_ENABLED=true
# No embedding provider is configured on this VM, so automatic vector indexing
# would only produce failing background jobs. This matches the default
# documented in the kit's .env.example.
OM_DISABLE_VECTOR_SEARCH_AUTOINDEXING=true

# RATE_LIMIT_TRUST_PROXY_DEPTH is deliberately NOT set. It was tried at 2 and
# measured to make no difference: Traefik replaces X-Forwarded-For with the
# coolify bridge gateway, so the app's limiter finds no usable address at any
# depth and falls back to one shared bucket. The visitor's real address does
# arrive, in CF-Connecting-Ip, but the limiter does not read that header.
# See docker-compose.wan.yml for the measurements.
EOF

chmod 600 .env
echo "wrote .env for host ${HOST} (mode 600)"
